import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { scopeLegacyCss } from './legacy-css-scope.mjs';

export const legacyCssSources = [
  'app/workbench-repair.css',
  'app/components/campus/campus.css',
  'app/components/campus/shell.css',
  'app/components/campus/controls.css',
  'app/components/campus/surfaces.css',
  'app/components/campus/mobile.css',
  'app/components/campus/account.css',
  'app/components/campus/workspace-chrome.css',
  'app/components/campus/page-families.css',
];

export async function compileLegacyCss(projectRoot = process.cwd()) {
  const sections = [];
  for (const sourcePath of legacyCssSources) {
    const source = await readFile(resolve(projectRoot, sourcePath), 'utf8');
    const result = scopeLegacyCss(source, sourcePath);
    if (result.documentRules.length) {
      const locations = result.documentRules.map(item => `${sourcePath}:${item.line}`).join(', ');
      throw new Error(`Legacy document selectors must be moved to the legacy root before compilation: ${locations}`);
    }
    sections.push(`/* source: ${sourcePath} */\n${result.css.trim()}\n`);
  }
  return `/* Generated by scripts/build-legacy-css.mjs. Do not edit directly. */\n${sections.join('\n')}`;
}

async function main() {
  const projectRoot = process.cwd();
  const outputPath = resolve(projectRoot, 'app/styles/legacy-scoped.css');
  const compiled = await compileLegacyCss(projectRoot);
  if (process.argv.includes('--check')) {
    const current = await readFile(outputPath, 'utf8').catch(() => '');
    if (current !== compiled) throw new Error('app/styles/legacy-scoped.css is stale; run npm run css:legacy');
    return;
  }
  await mkdir(resolve(projectRoot, 'app/styles'), { recursive: true });
  await writeFile(outputPath, compiled, 'utf8');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
